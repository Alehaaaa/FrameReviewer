def normalized_path(path):
    """Host-independent comparison key; avoid resolving nonexistent patterns."""
    normalized = to_slashes(os.path.normpath(os.path.expanduser(
        os.path.expandvars(str(path or ''))))).rstrip('/')
    # Drive-letter and UNC paths are Windows-style even when a Linux review
    # workstation is resolving them. POSIX paths may be case sensitive.
    if re.match(r'^[a-zA-Z]:/', normalized) or normalized.startswith('//'):
        return normalized.casefold()
    return os.path.normcase(normalized)


def atomic_json_write(path, data):
    """Replace a JSON file atomically, leaving an existing file on failure."""
    path = os.path.abspath(os.path.expanduser(path))
    directory = os.path.dirname(path)
    if not os.path.isdir(directory):
        os.makedirs(directory)
    fd, temporary = tempfile.mkstemp(prefix='.' + os.path.basename(path) + '.',
                                     suffix='.tmp', dir=directory)
    try:
        with os.fdopen(fd, 'w', encoding='utf-8') as stream:
            json.dump(data, stream, indent=2, ensure_ascii=False, sort_keys=True)
            stream.write('\n')
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)
    return path


def _content_signature(session):
    """Stable review signature; navigating frames is not a review edit."""
    snapshot = session.to_dict()
    for source in snapshot.get('sources', []):
        review = source.get('review')
        if isinstance(review, dict):
            # Both keys move continuously with normal playback/scrubbing.
            # Excluding them avoids treating a moved playhead as an edit.
            review.pop('frame', None)
            review.pop('source_frame', None)
    return json.dumps(snapshot, sort_keys=True,
                      ensure_ascii=False, separators=(',', ':'), default=str)


_AUTOGENERATED_RECOVERY = re.compile(r'^session-[0-9a-f]{32}\.frsession$')

# Managed attachment ownership and location are a narrow, explicit contract.
# Never infer local ownership merely because an imported URI looks relative.
_ASSET_ROOT = '.framereviewer-assets'
_ASSET_MAX_BYTES = 128 * 1024 * 1024
_ASSET_TOTAL_BYTES = 256 * 1024 * 1024
_ASSET_MAX_COUNT = 256
_ASSET_NAME = re.compile(r'^[A-Za-z0-9_-]{1,96}(?:\.[a-z0-9]{1,12})?$')
_ASSET_SHA256 = re.compile(r'^[0-9a-f]{64}$')


def _canonical_local_path(path):
    """A filename with no traversal or virtual/network path interpretation."""
    if not isinstance(path, str) or not path or '\x00' in path or \
            path.startswith('//') or path.startswith('\\\\') or \
            re.match(r'^[A-Za-z][A-Za-z0-9+.-]*:', path):
        raise ValueError('Save As needs an ordinary local filesystem path.')
    expanded = os.path.expanduser(path)
    if any(part in ('.', '..') for part in expanded.split(os.sep)):
        raise ValueError('Session paths must not contain traversal or dot segments.')
    return os.path.abspath(expanded)


def _open_directory(path, create=False):
    """Traverse from the root with dir-fds, rejecting symlink components."""
    if not os.path.isabs(path) or os.path.normpath(path) != path:
        raise ValueError('Attachment relocation needs canonical absolute folders.')
    flags = os.O_RDONLY | getattr(os, 'O_DIRECTORY', 0) | getattr(os, 'O_NOFOLLOW', 0)
    fd = os.open(os.path.sep, flags)
    try:
        for component in path.split(os.sep)[1:]:
            if not component:
                continue
            if create:
                try:
                    os.mkdir(component, mode=0o700, dir_fd=fd)
                except FileExistsError:
                    pass
            next_fd = os.open(component, flags, dir_fd=fd)
            if not stat.S_ISDIR(os.fstat(next_fd).st_mode):
                os.close(next_fd)
                raise ValueError('Session asset parent is not a directory.')
            os.close(fd)
            fd = next_fd
        return fd
    except BaseException:
        os.close(fd)
        raise


def _asset_directory(root_fd, source_hash, create=False):
    """Enter only the two fixed, validated subdirectories below a session."""
    flags = os.O_RDONLY | getattr(os, 'O_DIRECTORY', 0) | getattr(os, 'O_NOFOLLOW', 0)
    current = os.dup(root_fd)
    try:
        for component in (_ASSET_ROOT, source_hash):
            if create:
                try:
                    os.mkdir(component, mode=0o700, dir_fd=current)
                except FileExistsError:
                    pass
            child = os.open(component, flags, dir_fd=current)
            os.close(current)
            current = child
        return current
    except BaseException:
        os.close(current)
        raise


def _asset_references(session):
    """Only typed, locally managed notes with verified canonical asset URIs.

    Other remote/absolute URLs are unchanged; unknown relative attachments
    fail closed on cross-directory Save As rather than creating broken links.
    """
    found = {}
    total = 0
    for source in session.sources:
        review = source.review or {}
        records = review.get('review_records')
        if records is None:
            continue
        if not isinstance(records, dict) or not isinstance(records.get('notes'), list):
            raise ValueError('Cannot verify review attachment records for relocation.')
        embedded = records.get('review_records')
        if embedded is not None:
            if (not isinstance(embedded, dict) or
                    embedded.get('notes') != records['notes']):
                raise ValueError('Embedded rich review attachments disagree with canonical notes.')
        if not isinstance(records.get('source'), dict) or \
                records['source'].get('id') != source.id:
            raise ValueError('Review attachment source identity differs from session source.')
        source_hash = hashlib.sha256(source.id.encode('utf-8')).hexdigest()[:24]
        for note in records['notes']:
            if not isinstance(note, dict) or not isinstance(note.get('attachments', []), list):
                raise ValueError('Cannot verify typed review attachment list.')
            if note.get('source_id', source.id) != source.id:
                raise ValueError('Attachment note belongs to a different source.')
            for attachment in note.get('attachments', []):
                if not isinstance(attachment, dict):
                    raise ValueError('Review attachment is not typed metadata.')
                uri = attachment.get('uri')
                if not isinstance(uri, str) or not uri:
                    raise ValueError('Review attachment has no trustworthy URI.')
                if attachment.get('fr_managed_asset') is not True:
                    if uri.startswith(_ASSET_ROOT) or (
                            not os.path.isabs(uri) and
                            not re.match(r'^[A-Za-z][A-Za-z0-9+.-]*:', uri)):
                        raise ValueError('Unowned relative attachment cannot move to another session folder.')
                    continue
                attachment_id = attachment.get('id')
                parts = uri.split('/')
                if (len(parts) != 3 or parts[0] != _ASSET_ROOT or
                        parts[1] != source_hash or
                        not _ASSET_NAME.fullmatch(parts[2]) or
                        not isinstance(attachment_id, str) or
                        not (parts[2] == attachment_id or
                             parts[2].startswith(attachment_id + '.'))):
                    raise ValueError('Managed attachment URI is not source-scoped and canonical.')
                digest = attachment.get('sha256')
                size = attachment.get('size_bytes')
                if (type(size) is not int or not 0 <= size <= _ASSET_MAX_BYTES or
                        not isinstance(digest, str) or
                        not _ASSET_SHA256.fullmatch(digest)):
                    raise ValueError('Managed attachment needs a bounded size and SHA256 proof.')
                current = found.get(uri)
                if current is not None:
                    if current != (size, digest):
                        raise ValueError('Conflicting attachment proofs for one source asset.')
                    continue
                if len(found) >= _ASSET_MAX_COUNT or total + size > _ASSET_TOTAL_BYTES:
                    raise ValueError('Managed attachment relocation exceeds bounded budget.')
                found[uri] = (size, digest)
                total += size
    return found


def _checked_asset(fd, expected_size, expected_digest):
    """SHA256 a bounded regular opened file (never trust a symlink)."""
    info = os.fstat(fd)
    if not stat.S_ISREG(info.st_mode) or info.st_size != expected_size:
        raise ValueError('Managed attachment differs from frozen size or file type.')
    hasher = hashlib.sha256()
    read = 0
    while True:
        part = os.read(fd, min(1024 * 1024, expected_size + 1 - read))
        if not part:
            break
        read += len(part)
        if read > expected_size:
            raise ValueError('Managed attachment grew during verification.')
        hasher.update(part)
    if read != expected_size or hasher.hexdigest() != expected_digest:
        raise ValueError('Managed attachment SHA256 mismatch.')
    after = os.fstat(fd)
    if (after.st_size, after.st_mtime_ns) != (info.st_size, info.st_mtime_ns):
        raise ValueError('Managed attachment changed during verification.')


def _copy_asset(old_fd, new_fd, filename, expected_size, digest, created):
    """Exclusive, no-follow copy or verified-identical target; no predelete."""
    flags = os.O_RDONLY | getattr(os, 'O_NOFOLLOW', 0) | getattr(os, 'O_NONBLOCK', 0)
    source_fd = os.open(filename, flags, dir_fd=old_fd)
    try:
        _checked_asset(source_fd, expected_size, digest)
        os.lseek(source_fd, 0, os.SEEK_SET)
        destination_copy_fd = os.dup(new_fd)
        try:
            output_fd = os.open(filename,
                                os.O_WRONLY | os.O_CREAT | os.O_EXCL |
                                getattr(os, 'O_NOFOLLOW', 0), 0o600,
                                dir_fd=new_fd)
        except FileExistsError:
            os.close(destination_copy_fd)
            existing_fd = os.open(filename, flags, dir_fd=new_fd)
            try:
                try:
                    _checked_asset(existing_fd, expected_size, digest)
                except ValueError as exc:
                    raise FileExistsError('Existing destination attachment differs: {}'.format(
                        filename)) from exc
            finally:
                os.close(existing_fd)
            return
        except BaseException:
            os.close(destination_copy_fd)
            raise
        # Register immediately: a short write/cancellation must roll back
        # this inode, but never any pre-existing or independently replaced file.
        info = os.fstat(output_fd)
        created.append((destination_copy_fd, filename, info.st_dev, info.st_ino))
        try:
            hasher = hashlib.sha256()
            copied = 0
            while True:
                chunk = os.read(source_fd, min(1024 * 1024, expected_size + 1 - copied))
                if not chunk:
                    break
                copied += len(chunk)
                if copied > expected_size:
                    raise ValueError('Managed source grew while copying.')
                hasher.update(chunk)
                with memoryview(chunk) as pending:
                    while pending:
                        amount = os.write(output_fd, pending)
                        if amount <= 0:
                            raise OSError('Managed asset write stopped.')
                        pending = pending[amount:]
            if copied != expected_size or hasher.hexdigest() != digest:
                raise ValueError('Managed source changed while copying.')
            os.fsync(output_fd)
        finally:
            os.close(output_fd)
        verify_fd = os.open(filename, flags, dir_fd=new_fd)
        try:
            _checked_asset(verify_fd, expected_size, digest)
        finally:
            os.close(verify_fd)
    finally:
        os.close(source_fd)


def _rollback_new_assets(created):
    """Only unlink exact inodes exclusively created by this Save As."""
    for fd, name, device, inode in reversed(created):
        try:
            info = os.stat(name, dir_fd=fd, follow_symlinks=False)
            if (info.st_dev, info.st_ino) == (device, inode) and \
                    stat.S_ISREG(info.st_mode):
                os.unlink(name, dir_fd=fd)
        except FileNotFoundError:
            pass
        finally:
            os.close(fd)
    created.clear()


def _secure_json_commit(destination_fd, basename, data):
    """Atomic JSON commit using the already verified destination directory."""
    try:
        existing = os.stat(basename, dir_fd=destination_fd, follow_symlinks=False)
    except FileNotFoundError:
        existing = None
    if existing is not None and not stat.S_ISREG(existing.st_mode):
        raise ValueError('Save As destination must not be a symlink or special file.')
    temporary = '.{}.{}.tmp'.format(basename, uuid.uuid4().hex)
    fd = os.open(temporary, os.O_WRONLY | os.O_CREAT | os.O_EXCL |
                 getattr(os, 'O_NOFOLLOW', 0), 0o600, dir_fd=destination_fd)
    try:
        with os.fdopen(fd, 'w', encoding='utf-8') as stream:
            json.dump(data, stream, indent=2, ensure_ascii=False, sort_keys=True)
            stream.write('\n')
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary, basename, src_dir_fd=destination_fd,
                   dst_dir_fd=destination_fd)
    finally:
        try:
            os.unlink(temporary, dir_fd=destination_fd)
        except FileNotFoundError:
            pass


def _save_with_relocated_assets(previous, destination, session, payload):
    """Stage verified local assets, then commit session JSON; rollback on error."""
    references = _asset_references(session)
    if not references:
        # An ordinary session (or one with remote absolute/URL attachments)
        # has nothing to relocate. Preserve pre-existing Save As semantics,
        # including standard macOS temp paths whose /var alias is a symlink.
        return atomic_json_write(destination, payload)
    old = _canonical_local_path(previous) if previous else None
    new = _canonical_local_path(destination)
    if references and old is None:
        raise ValueError('Cannot relocate managed attachments without a named saved source session.')
    created = []
    origin_fd = None
    destination_fd = None
    succeeded = False
    try:
        if old:
            origin_fd = _open_directory(os.path.dirname(old))
            previous_info = os.stat(os.path.basename(old), dir_fd=origin_fd,
                                    follow_symlinks=False)
            if not stat.S_ISREG(previous_info.st_mode):
                raise ValueError('Previous named session is not a regular file.')
        destination_fd = _open_directory(os.path.dirname(new), create=True)
        for uri, (size, digest) in references.items():
            _, source_hash, filename = uri.split('/')
            src_folder = _asset_directory(origin_fd, source_hash)
            try:
                dst_folder = _asset_directory(destination_fd, source_hash,
                                              create=True)
                try:
                    _copy_asset(src_folder, dst_folder, filename, size, digest,
                                created)
                finally:
                    os.close(dst_folder)
            finally:
                os.close(src_folder)
        _secure_json_commit(destination_fd, os.path.basename(new), payload)
        succeeded = True
    finally:
        if not succeeded:
            _rollback_new_assets(created)
        else:
            for fd, _, _, _ in created:
                os.close(fd)
        if destination_fd is not None:
            os.close(destination_fd)
        if origin_fd is not None:
            os.close(origin_fd)


def prune_auto_recoveries(folder, keep=3):
    """Keep at most three automatically generated, unnamed recoveries.

    Never remove an explicitly saved session or its named autosave sidecar.
    """
    if not os.path.isdir(folder):
        return 0
    candidates = []
    for name in os.listdir(folder):
        if not _AUTOGENERATED_RECOVERY.fullmatch(name):
            continue
        path = os.path.join(folder, name)
        if not os.path.isfile(path) or os.path.islink(path):
            continue
        try:
            candidates.append((os.path.getmtime(path), path))
        except OSError:
            continue
    candidates.sort(reverse=True)
    deleted = 0
    for _, path in candidates[max(0, int(keep)):]:
        try:
            os.unlink(path)
            deleted += 1
        except OSError:
            pass
    return deleted


class SessionController(object):
    """Central session state, deliberately independent of Qt/Maya."""

    def __init__(self, session=None, path=None, mapper=None):
        self.session = session or Session()
        self.path = path
        self.mapper = mapper or PathMapper.from_env()
        self.dirty = False
        self._envelope = None
        self._saved_content = _content_signature(self.session)
        self._recovery_content = None
        self._recovery_destination = None

    @property
    def current(self):
        return self.session.current_source()

    def source_for_path(self, path):
        wanted = normalized_path(path)
        if not wanted:
            return None
        for source in self.session.sources:
            for rep in source.representations:
                if (normalized_path(rep.path) == wanted or
                        normalized_path(self.mapper.map(rep.path)) == wanted):
                    return source
        return None

    def reconcile_info(self, info, source_id=None, role=ROLE_ORIGINAL,
                       select=True):
        """Use supplied source ID first, representation path second.

        A new representation updates media/timing without replacing review
        notes, markers or crop. Existing IDs always take precedence over paths.
        """
        source = self.session.source(source_id) if source_id else None
        if source is None:
            source = self.source_for_path(info.path)
        if source is None:
            source = self.session.add_source(Source.from_media_info(info, role=role))
            if source_id:
                # A stable studio entity/Sequencer shot ID is authoritative even
                # before its first representation exists in a new session.
                source.id = str(source_id)
                if self.session.current_source_id != source.id and len(self.session.sources) == 1:
                    self.session.current_source_id = source.id
            self.dirty = True
        else:
            kind = KIND_SEQUENCE if getattr(info, 'is_sequence', False) else KIND_MOVIE
            rep = source.representation(role)
            if rep is None or normalized_path(rep.path) != normalized_path(info.path):
                # An explicit ID may designate a genuinely new version.
                if rep is None:
                    source.relink(role, info.path, kind=kind)
                elif source_id:
                    source.relink(role, info.path, kind=kind)
                else:
                    # Path matched an alternate representation: keep its role.
                    rep = next((r for r in source.representations
                                if normalized_path(r.path) == normalized_path(info.path)), rep)
                    role = rep.role
                self.dirty = True
            if source.active_role != role:
                source.set_active_role(role)
                self.dirty = True
            # Version switches are real: timing/metadata belong to that media.
            updated = Source.from_media_info(info, role=role)
            if source.timing != updated.timing:
                source.timing = updated.timing
                self.dirty = True
            source.metadata.update(updated.metadata)
            if updated.audio:
                # Probing a switched representation must not erase the
                # reviewer's chosen external soundtrack / stream offset.
                existing_audio = dict(source.audio or {})
                existing_audio.update(updated.audio)
                if existing_audio != source.audio:
                    source.audio = existing_audio
                    self.dirty = True
        if select and self.session.current_source_id != source.id:
            self.session.set_current(source.id)
            self.dirty = True
        return source

    def set_current(self, source_id):
        if source_id != self.session.current_source_id:
            self.session.set_current(source_id)
            self.dirty = True
        return self.current

    def update_review(self, state, source_id=None):
        source = self.session.source(source_id) if source_id else self.current
        if source is None:
            return False
        updated = dict(source.review)
        updated.update(copy.deepcopy(state))
        if updated == source.review:
            return False
        source.review = updated
        self.dirty = True
        return True

    def update_source_metadata(self, changes, source_id=None):
        """Persist studio/remote identity without conflating it with review UI.

        Namespaced metadata such as ``shotgrid`` follows a stable Source.id,
        not whichever movie/proxy is currently selected as representation.
        """
        source = self.session.source(source_id) if source_id else self.current
        if source is None:
            return False
        updated = copy.deepcopy(source.metadata)
        updated.update(copy.deepcopy(changes))
        if updated == source.metadata:
            return False
        source.metadata = updated
        self.dirty = True
        return True

    def set_view(self, **changes):
        updated = dict(self.session.view)
        updated.update(changes)
        if updated != self.session.view:
            self.session.view = updated
            self.dirty = True

    def remove_source(self, source_id):
        if self.session.source(source_id) is not None:
            self.session.remove_source(source_id)
            self.dirty = True

    def reorder(self, ids):
        chosen = set(ids)
        current = self.session.sources
        by_id = {source.id: source for source in current}
        ordered = [by_id[id] for id in ids if id in by_id]
        ordered.extend(source for source in current if source.id not in chosen)
        if [source.id for source in ordered] != [source.id for source in current]:
            self.session.sources = ordered
            self.dirty = True

    def resolved_path(self, source, role=None):
        rep = source.representation(role) if role else source.active_representation()
        return self.mapper.map_existing(rep.path) if rep else None

    def choose_representation(self, source_id, requested_role='automatic'):
        """Switch version using one stable source and a verified local path."""
        source = self.session.source(source_id)
        if source is None:
            raise KeyError('Unknown source ID: {}'.format(source_id))
        if requested_role == 'automatic':
            order = ('review', 'published', 'proxy', 'playblast', 'exr', 'original')
            available = [rep for rep in source.representations
                         if self.mapper.map_existing(rep.path) and
                         os.path.exists(self.mapper.map_existing(rep.path))]
            if not available:
                raise IOError('No reachable representation for {}'.format(source.name))
            chosen = min(available, key=lambda rep: (
                order.index(rep.role) if rep.role in order else len(order)))
        else:
            chosen = source.representation(requested_role)
            if chosen is None:
                raise ValueError('{} has no {} representation.'.format(
                    source.name, requested_role))
        if source.active_role != chosen.role:
            source.set_active_role(chosen.role)
            self.dirty = True
        return chosen

    def payload(self):
        # Preserve unknown top-level fields, original creation metadata and
        # generator details from a session authored by a newer studio plugin.
        payload = copy.deepcopy(self._envelope) if self._envelope else build_payload(self.session)
        payload['session'] = self.session.to_dict()
        if self.has_unsaved_changes():
            payload['modified'] = _now()
        return payload

    def has_unsaved_changes(self):
        """Detect real review edits, even if a dirty flag was set redundantly."""
        return _content_signature(self.session) != self._saved_content

    def save(self, path=None):
        destination = path or self.path
        if not destination:
            raise ValueError('Choose a .frsession destination first.')
        if not destination.lower().endswith('.frsession'):
            destination += '.frsession'
        payload = self.payload()
        old_folder = (os.path.dirname(os.path.abspath(self.path))
                      if self.path else None)
        new_folder = os.path.dirname(os.path.abspath(destination))
        if old_folder is not None and os.path.normcase(old_folder) == os.path.normcase(new_folder):
            # Same-directory Save/Save As leaves already-relative assets in
            # place; do not add extra autosave writes or copy work.
            atomic_json_write(destination, payload)
        else:
            _save_with_relocated_assets(self.path, destination,
                                        self.session, payload)
        self.path = os.path.abspath(destination)
        self._envelope = payload
        self.dirty = False
        self._saved_content = _content_signature(self.session)
        # Manual saving supersedes this session's autosave. Only clean up a
        # checkpoint we created ourselves, never unrelated review files.
        recovery = self._recovery_destination
        if recovery and os.path.isfile(recovery):
            try:
                os.unlink(recovery)
            except OSError:
                pass
        self._recovery_content = None
        self._recovery_destination = None
        return self.path

    def save_recovery(self, path):
        """Return True only when a changed session required a disk write."""
        if not self.has_unsaved_changes():
            self.dirty = False
            return False
        signature = _content_signature(self.session)
        destination = os.path.abspath(os.path.expanduser(path))
        if (self._recovery_content == signature and
                self._recovery_destination == destination and
                os.path.isfile(destination)):
            return False
        if os.path.isfile(destination):
            # Even across a hot reload, do not rewrite an identical autosave.
            try:
                with open(destination, 'r', encoding='utf-8') as stream:
                    existing = json.load(stream)
                if (existing['session']['id'] == self.session.id and
                        _content_signature(Session.from_dict(existing['session'])) == signature):
                    self._recovery_content = signature
                    self._recovery_destination = destination
                    return False
            except (OSError, IOError, KeyError, ValueError, TypeError):
                pass
        atomic_json_write(destination, self.payload())
        self._recovery_content = signature
        self._recovery_destination = destination
        if _AUTOGENERATED_RECOVERY.fullmatch(os.path.basename(destination)):
            prune_auto_recoveries(os.path.dirname(destination))
        return True

    def open(self, path):
        with open(path, 'r', encoding='utf-8') as stream:
            payload = json.load(stream)
        loaded = parse_payload(payload)  # validate before replacing live state
        self.session = loaded
        self._envelope = copy.deepcopy(payload)
        self.path = os.path.abspath(path)
        self.dirty = False
        self._saved_content = _content_signature(self.session)
        self._recovery_content = None
        self._recovery_destination = None
        return loaded

    def restore_snapshot(self, payload):
        """Load embedded Maya state; leave disk file association unchanged."""
        loaded = parse_payload(payload)
        self.session = loaded
        self._envelope = copy.deepcopy(payload)
        self.dirty = False
        self._saved_content = _content_signature(self.session)
        self._recovery_content = None
        self._recovery_destination = None
        return loaded

    def replace_session(self, session):
        """Start an imported/constructed session without leaking prior file data.

        This is not ``open``: the new session has never been explicitly saved,
        so it must be considered unsaved and must not inherit unknown envelope
        fields, a previous session path, or the previous recovery checkpoint.
        """
        if not isinstance(session, Session):
            raise TypeError('Expected a Session.')
        self.session = session
        self.path = None
        self._envelope = None
        self.dirty = True
        self._saved_content = None
        self._recovery_content = None
        self._recovery_destination = None
        return session

