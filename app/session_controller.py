# -*- coding: utf-8 -*-
"""Qt-free live review session, stable source identity and atomic persistence.

The controller is the authoritative owner of portable state. Widgets may cache
presentation details, but media relinks and playlist edits retain source IDs.
"""
from __future__ import absolute_import

import copy
import hashlib
import json
import os
import re
import stat
import tempfile
import uuid

from .session import (Session, Source, ROLE_ORIGINAL, KIND_MOVIE,
                      KIND_SEQUENCE, build_payload, parse_payload, _now)
